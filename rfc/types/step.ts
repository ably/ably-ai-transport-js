import type { AnyCodec, CodecEvent, CodecMessage, CodecPart } from './codec.js';
import type { SendEventsTarget } from './run.js';
import type { ABORTED, PAUSED } from './signal-reason.js';

/** Terminal status for a step. */
export type StepEndStatus = 'complete' | 'failed' | 'aborted' | 'paused' | 'superseded';

/**
 * All possible step statuses including non-terminal states.
 *
 * `'pending'` is the pre-start status of a local step handle — a step
 * returned by `run.createStep()` before `start()` has resolved. It is
 * only reachable through a live in-memory handle; `'pending'` is never
 * materialised on the channel (a pending step has not published
 * `x-ably-step-start`), so it will not appear on `StepState.status` in
 * the tree.
 */
export type StepStatus = StepEndStatus | 'pending' | 'active' | 'abandoned';

/** Readable step state in the materialised tree. */
export interface StepState {
  /** The step's unique ID, generated by the agent on `x-ably-step-start`. */
  readonly id: string;
  /** The run this step belongs to. */
  readonly runId: string;
  /** Current status of the step. */
  readonly status: StepStatus;
  /**
   * Signal reason captured at `step.end()` time — whichever sentinel
   * (`ABORTED` or `PAUSED`) was set on `step.signal.reason` when the
   * step finalised, or `undefined` if the signal never aborted.
   *
   * Consumed by the run terminal classifier (`run.end()` reads
   * `lastStep.signalReason` to distinguish the case-(a) pattern where a
   * step completes normally despite an observed pause from the
   * post-completion happy path). Exposed publicly for symmetric
   * observability with `status` (telemetry, debug UI explaining why a
   * run suspended).
   */
  readonly signalReason?: typeof ABORTED | typeof PAUSED;
}

/**
 * Options accepted by {@link Step.start}.
 */
export interface StepStartOptions {
  /**
   * Abort the precondition wait after this many milliseconds. Defaults to
   * `60_000` when neither `timeoutMs` nor `signal` is supplied — prevents
   * a hop from hanging forever waiting for an invocation message that
   * never arrives.
   */
  timeoutMs?: number;

  /**
   * Caller-supplied abort signal folded into {@link Step.signal}. After
   * `start()` resolves, `step.signal.aborted` becomes true whenever this
   * signal fires OR when an `x-ably-abort` control signal is observed
   * on the channel. Callers wire runtime-owned cancellation in here
   * (`req.signal` in serverless handlers, a WDK `abortSignal` in durable
   * execution) — the SDK does not introspect the runtime and composes
   * only what the caller hands it.
   */
  signal?: AbortSignal;
}

/**
 * The agent's active write handle for one continuous execution within a run.
 * Created from an {@link AgentRun} via run.createStep(). The run carries the
 * invocation and exposes the conversation to pass to the model (via
 * `run.view.messages`); the step is the execution surface — it owns the
 * abort signal, the pause handler, and the write methods (pipe,
 * sendMessages, sendParts, sendEvents).
 *
 * Both Session and Step implement AsyncDisposable for scope-based cleanup
 * in serverless functions:
 *
 *   await using step = run.createStep();
 *
 * Parameterised by the session's codec — `C extends Codec<TPart, TMessage,
 * TEvent>` — matching {@link ClientRun} so callers name the variant with a
 * single type argument.
 */
export interface Step<C extends AnyCodec> {
  /** The step's unique ID, generated when the step is created. */
  readonly id: string;

  /**
   * Current status of the step — mirrors {@link StepState.status} once the
   * step is materialised on the channel. A freshly created step handle is
   * `'pending'` until {@link Step.start} resolves, at which point it
   * transitions to `'active'`. If `start()` rejects, the handle remains
   * `'pending'` and the disposer is a no-op ({@link Step[Symbol.asyncDispose]}).
   */
  readonly status: StepStatus;

  /**
   * Composed cancellation signal. Aborts when any of the following happens:
   *   - An `x-ably-abort` control signal is observed on the channel
   *     (the durable "run aborted" fact). `signal.reason` is `ABORTED`.
   *   - An `x-ably-pause` control signal is observed on the channel
   *     (the durable "run paused" fact). `signal.reason` is `PAUSED`.
   *   - A signal passed to {@link Step.start} via `start({ signal })` fires
   *     (the caller folds in runtime-owned cancellation: `req.signal` in
   *     serverless handlers, a WDK `abortSignal` in durable execution).
   *     `signal.reason` is `ABORTED`.
   *   - The precondition wait exceeds `timeoutMs`. `signal.reason` is
   *     `ABORTED`.
   *
   * Wire into your model call as `abortSignal: step.signal` for the common
   * case ("any cancellation interrupts the stream"). The terminal-status
   * inference at `step.end(error?)` reads `signal.reason` to pick
   * between `'aborted'` and `'paused'`. Reach for {@link Step.abortSignal}
   * instead when pause should *not* interrupt the in-flight work.
   *
   * If the run was aborted or paused before this step started, the
   * signal is already aborted when {@link Step.start} resolves with
   * `signal.reason` populated.
   *
   * The `ABORTED` and `PAUSED` sentinels are exported from the package
   * root.
   */
  readonly signal: AbortSignal;

  /**
   * Narrow cancellation signal. Aborts only on hard-abort sources —
   * `x-ably-abort`, caller-folded `start({ signal })`, and the precondition
   * timeout. **Never aborts on pause.**
   *
   * Wire into your model call as `abortSignal: step.abortSignal` when the
   * handler wants pause to be observed but **not** interrupt the in-flight
   * stream (the case-(a) pattern: let the current response finish, then
   * suspend the run for later resume). The pause is still reflected on
   * `step.signal.reason === PAUSED` and frozen onto `StepState.signalReason`
   * at `step.end()` time, so `run.end()` can route correctly.
   */
  readonly abortSignal: AbortSignal;

  /**
   * Wait for all preconditions declared in the view's invocation to be
   * visible in the session, then publish `x-ably-step-start` to the channel.
   * Resolves when the step is active and the view's messages are complete.
   *
   * If a pre-existing abort signal is found in the session (published while
   * no agent was running), `signal.aborted` will be true after `start()`
   * resolves. If a pre-existing pause signal is found, any `'pause'` handler
   * already registered fires immediately after `start()` resolves; handlers
   * registered later also receive the buffered signal on first subscription
   * (see {@link Step.on}).
   *
   * On successful resolution the step transitions from `'pending'` to
   * `'active'`. If `start()` rejects, the step remains `'pending'` — no
   * `x-ably-step-start` reached the channel, and the disposer is a no-op.
   *
   * If the targeted run is `'suspended'` when `start()` is called, a
   * successful `x-ably-step-start` publish implicitly transitions the run
   * to `'active'`. Publishing `x-ably-resume` is not required to ungate
   * `start()`; the resume control signal exists to *wake* an agent (drive
   * a new step-start externally when none would otherwise fire) rather
   * than to gate step-start itself.
   * @param options - Precondition-wait timeout and caller-folded abort
   *   signal; see {@link StepStartOptions}.
   * @throws An `Ably.ErrorInfo` with code:
   *   - {@link ErrorCode.StepSuperseded} — another `x-ably-step-start`
   *     with an earlier serial was observed for the same run (a sibling
   *     hop won).
   *   - {@link ErrorCode.InvocationPreconditionTimeout} — the precondition
   *     wait exceeded `timeoutMs`.
   *   - {@link ErrorCode.StepStartAborted} — the caller-supplied
   *     `options.signal` fired before preconditions were met.
   */
  start(options?: StepStartOptions): Promise<void>;

  /**
   * Finalise the step. Publishes `x-ably-step-end` with the terminal
   * status the SDK derives from the inputs and releases step resources
   * (signal listeners, stream references). The chosen status is also
   * frozen onto `StepState.signalReason` for the run classifier.
   *
   * Inference table (single-method, single-argument; no explicit-status
   * overload):
   *
   * | Inputs                                                | Step terminal |
   * | ----------------------------------------------------- | ------------- |
   * | `error === undefined`, `!signal.aborted`              | `'complete'`  |
   * | `error === undefined`, `signal.aborted` (late)        | `'complete'`  |
   * | `error !== undefined`, `signal.reason === ABORTED`    | `'aborted'`   |
   * | `error !== undefined`, `signal.reason === PAUSED`     | `'paused'`    |
   * | `error !== undefined`, `signal.aborted`, other reason | `'aborted'`   |
   * | `error !== undefined`, `!signal.aborted`              | `'failed'`    |
   *
   * Pass the caught error from a `catch` block to `end(error)`; pass no
   * argument from the happy path. Observable-outcome rules: a late abort
   * or pause that arrives after the handler decided "done" cannot unwind
   * completed work, so `error === undefined` always classifies as
   * `'complete'`.
   *
   * On `'failed'`, the SDK serialises `error.message` (and, when `error`
   * is an `Ably.ErrorInfo`, its `code`) onto the `x-ably-step-end`
   * headers for downstream observability.
   *
   * Idempotent on a step that has already reached a terminal status —
   * publishes nothing and resolves `void`. No-op when the step is still
   * `'pending'` (`start()` never resolved, so no `x-ably-step-start`
   * reached the channel).
   *
   * `'superseded'` and `'abandoned'` are SDK-derived: `'superseded'` is
   * picked automatically when a concurrent `step-start` wins the race;
   * `'abandoned'` is a tree-side classification for orphaned steps and
   * is never wire-published. Neither is reachable from `end()`.
   * @param error - The caught error, or omitted on the happy path.
   */
  end(error?: unknown): Promise<void>;

  /**
   * Symbol.asyncDispose — pessimistic safety net. Behaviour depends on
   * {@link Step.status} at dispose time:
   *
   *   - `'pending'` → no-op. `start()` never resolved successfully, so the
   *     channel has no record of this step; publishing a `step-end` for a
   *     step it never saw a `step-start` for would emit garbage on the wire.
   *   - `'active'` → publishes a terminal `x-ably-step-end` so the channel
   *     state does not leak a half-open step:
   *     - `step.signal.aborted` is true → publishes `step.end('aborted')`.
   *     - Otherwise → publishes `step.end('failed')` with cause
   *       {@link ErrorCode.StepDisposedBeforeEnd} (`104021`).
   *   - Terminal (any {@link StepEndStatus}) → pure cleanup, no publish.
   *     The idempotent `end()` contract means an explicit earlier
   *     `end()` call is not clobbered.
   *
   * Callers still call `step.end()` (or `step.end(error)` from a catch)
   * on the explicit path; the disposer exists to close out runs that
   * leave scope via a thrown error before the explicit call ran.
   */
  [Symbol.asyncDispose](): Promise<void>;

  /**
   * Register a handler for a pause signal observed on the channel. The
   * agent can checkpoint state and end the step with `'paused'`, or let the
   * current work complete and end with `'complete'`.
   *
   * Fires on the same underlying `ControlSignal` (type `'pause'`) that
   * `Tree.on('control-signal', ...)` delivers; this is the step-scoped
   * ergonomic shortcut. Reach for the tree event when the full signal
   * object is needed (telemetry, debug, observing signals for runs other
   * than this step's).
   *
   * Pause signals are buffered: any pause observed before a handler is
   * registered (including signals materialised during `start()`) is
   * delivered synchronously to the handler on first subscription. This
   * removes the order-sensitive "register before `start()`" footgun —
   * handlers can be registered at any point and will still see prior
   * pauses.
   */
  on(event: 'pause', handler: () => void): void;

  /** Remove a previously registered pause handler. */
  off(event: 'pause', handler: () => void): void;

  /**
   * Pipe a readable stream through the codec encoder to the channel.
   * Each part is encoded and published as it arrives. The step's abort
   * signal is wired in automatically — if the run is aborted mid-pipe,
   * the stream is cancelled.
   */
  pipe(stream: ReadableStream<CodecPart<C>>): Promise<void>;

  /**
   * Publish one or more complete domain messages through the codec encoder.
   * Encoded via the codec's writeMessages path. Use for complete messages
   * like structured responses.
   *
   * **Same-ID republish is an in-place update.** When a message is published
   * whose ID already identifies a node in the session, the transport routes
   * it through {@link Accumulator.setMessage} and the tree fires
   * `'message-updated'` (not `'message-added'`). Publishing a message with a
   * fresh ID appends a new node. Use {@link Step.sendEvents} for additive
   * state transitions on an existing message rather than a full-message
   * republish.
   *
   * Tree nodes from a step publish are always recorded with protocol role
   * `'assistant'` ({@link MessageNode.role}); the domain-level role inside
   * the codec's `TMessage` is opaque to the transport.
   */
  sendMessages(messages: CodecMessage<C> | CodecMessage<C>[]): Promise<void>;

  /**
   * Publish one or more discrete domain parts through the codec encoder.
   * Encoded via the codec's writePart path. Use for standalone parts
   * like data-* that are not complete messages.
   */
  sendParts(parts: CodecPart<C> | CodecPart<C>[]): Promise<void>;

  /**
   * Publish one or more codec events through the codec encoder. Symmetric
   * with {@link ClientRun.sendEvents} but published from the agent side —
   * lets the agent emit codec-defined operations that neither stream as
   * chunks nor are complete messages. The shape of the codec's `TEvent` is
   * whatever the codec declares; the transport treats it opaquely.
   *
   * When `target.messageId` is supplied the transport tags the wire message
   * with `x-ably-msg-id` so the codec's accumulator can locate and mutate
   * the composed state of the target message. When omitted the event is
   * free-floating and its semantics are codec-specific. If the codec does
   * not declare a `TEvent` (i.e. defaults to `never`), this method is
   * uncallable.
   */
  sendEvents(events: CodecEvent<C> | CodecEvent<C>[], target?: SendEventsTarget): Promise<void>;
}
