/**
 * Lifecycle status of a run.
 *
 * Phase 11 subset of the RFC's `RunStatus` — `'suspended'` is deferred
 * and joins this union additively when durable pause control signals
 * land.
 */
export type RunStatus = 'active' | 'complete' | 'failed' | 'aborted';

/**
 * Terminal status accepted by run-end wire messages.
 *
 * Phase 11 subset of the RFC's `RunEndStatus` — `'aborted'` is wired to
 * the abort row of {@link AgentRun.end}'s classifier (when the bound
 * step's `signal.reason` is `ABORTED`).
 */
export type RunEndStatus = 'complete' | 'failed' | 'aborted';

/**
 * Read-only state of a run, common to both client and agent perspectives.
 *
 * Phase 5 subset of the RFC's `Run<TMessage>` — `messages`, `lastStep`,
 * `steps`, `suspendReason`, `when`, and `toInvocation` are deferred and
 * land in later phases (`messages`/`steps` once the tree links nodes to
 * their owning run; `when`/`toInvocation` alongside the run handles in
 * phases 6 and 7).
 *
 * Generic over `TMessage` so future phases can add `messages:
 * MessageNode<TMessage>[]` without re-shaping the type parameter.
 */
// eslint-disable-next-line @typescript-eslint/no-unused-vars -- TMessage reserved for additive phase-6+ members.
export interface Run<TMessage> {
  /** The run's unique ID, generated by the initiator on `x-ably-run-start`. */
  readonly id: string;

  /**
   * Current status of the run. When {@link abortRequested} is `true`, this
   * is always `'aborted'` — the abort control signal is itself the run
   * terminal, and tree synthesis prefers it over any later observed run-end
   * status. Spec: AIT-AB2.
   */
  readonly status: RunStatus;

  /**
   * `true` once an `x-ably-abort` control signal has been observed for this
   * run. Sticky — never clears. Drives the synthesised {@link status} of
   * `'aborted'` and is read by the run-end classifier on {@link AgentRun.end}.
   * Spec: AIT-AB2.
   */
  readonly abortRequested: boolean;

  /**
   * The clientId of the participant that opened this run. Taken from the
   * `x-ably-client-id` header on `x-ably-run-start` when a backend published
   * on behalf of an end-user; otherwise taken from the publishing
   * connection's `message.clientId`. Stable for the lifetime of the run.
   */
  readonly initiatorClientId: string;
}
